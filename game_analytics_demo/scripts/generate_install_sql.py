"""
Generate the install/NN-*.sql files that embed project sources.

The sources stay the single source of truth; re-run this after editing any of them:

  install/02-load-data.sql             data/<SCHEMA>/*.parquet + sql/<SCHEMA>/**.sql
  install/03-deploy-semantic-view.sql  semantic_views/*.yaml
  install/05-prime-query-history.sql   QUERIES in scripts/prime_query_history.py
  install/07-create-context.sql        context/scope.yaml
  install/08-record-feedback.sql       RECORDS in scripts/record_feedback.py
  install/09-deploy-agents.sql         agents/*.yaml
  install/10-load-eval-dataset.sql     evaluations/demo/demo_questions.yaml + *_demo_eval.yaml

install/01, 04, 06, 11 and 12 are written by hand. Every file is run from the repo root
(PUT paths are relative) with: snow sql -c <connection> --enable-templating NONE -f <file>

Usage: python3 scripts/generate_install_sql.py
"""
import importlib.util
import json
import pathlib
import re

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
INSTALL = ROOT / "install"
DB = "CORTEX_SENSE_DEMO"
SCHEMAS = ["GAME_CATALOG", "GAME_SALES"]
DATA_STAGE = f"{DB}.PUBLIC.DATA_STAGE"
FILE_FORMAT = f"{DB}.PUBLIC.PARQUET_FF"
# Object DDL types created after the base tables, in dependency order (see sorted_objects).
OBJECT_DIRS = ["functions", "procedures", "views", "dynamic_tables"]


def load_module(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def header(step, sources):
    return (f"-- {step}\n"
            f"-- GENERATED by scripts/generate_install_sql.py from {sources}. Do not edit by hand.\n"
            f"-- Run from the repo root: snow sql -c <connection> --enable-templating NONE -f install/{step}.sql\n\n")


def dollar(text, what):
    if "$$" in text:
        raise ValueError(f"{what} contains '$$', which breaks dollar-quoting")
    return f"$${text}$$"


def builder_call(action, params):
    """One SYSTEM$CORTEX_AGENT_CORTEX_CONTEXT_BUILDER call (one JSON string argument)."""
    payload = json.dumps({"action": action, "parameters": params}, ensure_ascii=False)
    return f"SELECT SYSTEM$CORTEX_AGENT_CORTEX_CONTEXT_BUILDER({dollar(payload, action)}) AS result;\n"


def ddl(path):
    text = path.read_text().strip()
    return text if text.endswith(";") else text + ";"


def sorted_objects():
    """Functions, procedures, views and dynamic tables, ordered so each comes after what it references."""
    objs = {}
    for s in SCHEMAS:
        for d in OBJECT_DIRS:
            for f in sorted((ROOT / "sql" / s / d).glob("*.sql")):
                objs[f.stem.upper()] = f
    deps = {name: {o for o in objs if o != name and re.search(rf"\b{o}\b", f.read_text(), re.I)}
            for name, f in objs.items()}
    out, done = [], set()

    def visit(name, path=()):
        if name in done:
            return
        if name in path:
            raise ValueError(f"Dependency cycle: {' -> '.join(path + (name,))}")
        for d in sorted(deps[name]):
            visit(d, path + (name,))
        done.add(name)
        out.append(objs[name])

    for name in objs:
        visit(name)
    return out


def gen_02():
    parts = [header("02-load-data", "data/ and sql/"),
             "-- Order: (a) upload parquet, (b) base tables, (c) COPY INTO, (d) functions, procedures,\n"
             "-- views and dynamic tables in dependency order. Table DDL is CREATE OR REPLACE.\n\n",
             "-- (a) Upload parquet files\n"]
    for s in SCHEMAS:
        parts.append(f"PUT 'file://data/{s}/*.parquet' @{DATA_STAGE}/{s}/ AUTO_COMPRESS = FALSE OVERWRITE = TRUE PARALLEL = 8;\n")
    parts.append("\n-- (b) Base tables\n")
    tables = [(s, f) for s in SCHEMAS for f in sorted((ROOT / "sql" / s / "tables").glob("*.sql"))
              if not f.stem.startswith("BACKUP_")]  # point-in-time backups, not part of the demo
    # A foreign key must reference a table that already exists, so referenced tables go first.
    names = {f"{s}.{f.stem}" for s, f in tables}
    fk_deps = {f"{s}.{f.stem}": set(re.findall(r"references\s+CORTEX_SENSE_DEMO\.(\w+\.\w+)", ddl(f), re.I))
               & names for s, f in tables}
    ordered = []
    def visit(n):
        if n not in ordered:
            for d in sorted(fk_deps[n] - {n}):
                visit(d)
            ordered.append(n)
    for s, f in tables:
        visit(f"{s}.{f.stem}")
    tables.sort(key=lambda sf: ordered.index(f"{sf[0]}.{sf[1].stem}"))
    for s, f in tables:
        parts.append(f"-- {s}.{f.stem}\n{ddl(f)}\n\n")
    parts.append("-- (c) Load each table that has a data file\n")
    for s, f in tables:
        t = f.stem
        if not list((ROOT / "data" / s).glob(f"{t}_[0-9]*.parquet")):
            parts.append(f"-- {s}.{t}: no data file, left empty\n")
            continue
        # PATTERN anchors on "/<TABLE>_<n>_" so PLATFORMS does not match GAME_PLATFORMS files.
        parts.append(
            f"COPY INTO {DB}.{s}.{t} FROM @{DATA_STAGE}/{s}/\n"
            f"  PATTERN = '(.*/)?{t}_[0-9]+_[0-9]+_[0-9]+[.]snappy[.]parquet'\n"
            f"  FILE_FORMAT = (FORMAT_NAME = '{FILE_FORMAT}')\n"
            f"  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = ABORT_STATEMENT;\n")
    parts.append("\n-- (d) Functions, procedures, views and dynamic tables\n")
    for f in sorted_objects():
        parts.append(f"-- {f.relative_to(ROOT / 'sql')}\n{ddl(f)}\n\n")
    return "".join(parts)


def sv_schema(model, path):
    schemas = {f"{t['base_table']['database']}.{t['base_table']['schema']}"
               for t in model.get("tables", []) if "base_table" in t}
    if len(schemas) != 1:
        raise ValueError(f"{path}: base tables span {sorted(schemas)}; can't pick a target schema")
    return schemas.pop()


def gen_03():
    parts = [header("03-deploy-semantic-view", "semantic_views/*.yaml")]
    for f in sorted((ROOT / "semantic_views").glob("*.y*ml")):
        text = f.read_text()
        schema = sv_schema(yaml.safe_load(text), f.name)
        parts.append(f"-- {f.name} -> {schema}.{yaml.safe_load(text)['name']} "
                     "(CREATE OR REPLACE ... COPY GRANTS)\n"
                     f"CALL SYSTEM$CREATE_SEMANTIC_VIEW_FROM_YAML('{schema}', {dollar(chr(10) + text + chr(10), f.name)}, FALSE, FALSE);\n\n")
    return "".join(parts)


def gen_05():
    prime = load_module("prime_query_history")
    parts = [header("05-prime-query-history", "QUERIES in scripts/prime_query_history.py"),
             "-- Rule-compliant queries Cortex Sense learns join patterns from. Rerunnable: each run adds\n"
             "-- more history. Run before the context build (07) so the build sees them.\n\n"]
    for label, sql in prime.QUERIES:
        parts.append(f"-- {label}\n{sql.strip()};\n\n")
    return "".join(parts)


def gen_07():
    fb = load_module("record_feedback")
    ctx = {"name": fb.CONTEXT, "database_name": fb.DB, "schema_name": fb.SCHEMA}
    scope = (ROOT / "context" / "scope.yaml").read_text()
    return (header("07-create-context", "context/scope.yaml")
            + f"-- Registers {fb.DB}.{fb.SCHEMA}.{fb.CONTEXT}, writes its scope and queues a build.\n"
              "-- \"already exists\" from create-context is fine on a re-run. The build runs in the background\n"
              "-- and takes a long time (often hours); install/11-check-context-build.sql reports when it's done.\n\n"
            + "-- 1. Register the context\n" + builder_call("create-context", ctx)
            + "\n-- 2. Write the scope (context/scope.yaml)\n"
            + builder_call("put-stage-file", {**ctx, "path": "scope.yaml", "content": scope, "overwrite": True})
            + "\n-- 3. Queue a build\n" + builder_call("force-reprocess", ctx))


def gen_08():
    fb = load_module("record_feedback")
    parts = [header("08-record-feedback", "RECORDS in scripts/record_feedback.py"),
             f"-- {len(fb.RECORDS)} business rules for {fb.DB}.{fb.SCHEMA}.{fb.CONTEXT}. Each is served as a\n"
             "-- correction as soon as it's recorded; no rebuild needed. Re-running records duplicates.\n\n"]
    for r in fb.RECORDS:
        params = {"name": fb.CONTEXT, "database_name": fb.DB, "schema_name": fb.SCHEMA,
                  **{k: r[k] for k in ("type", "raw_feedback", "feedback_rule", "indexed_text")}}
        params.update({k: r[k] for k in ("entity_keys", "concepts") if k in r})
        label = (r.get("concepts") or [r["type"]])[0]
        parts.append(f"-- {label}\n" + builder_call("record-feedback", params) + "\n")
    return "".join(parts)


def gen_09():
    parts = [header("09-deploy-agents", "agents/*.yaml")]
    for f in sorted((ROOT / "agents").glob("*.yaml")):
        parts.append(f"-- {f.name}\nCREATE OR REPLACE AGENT {DB}.AGENTS.{f.stem}\n"
                     f"  FROM SPECIFICATION {dollar(chr(10) + f.read_text() + chr(10), f.name)};\n\n")
    return "".join(parts)


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def gen_10():
    demo = ROOT / "evaluations" / "demo"
    configs = sorted(demo.glob("*_demo_eval.yaml"))
    datasets = {yaml.safe_load(c.read_text())["evaluation"]["source_metadata"]["dataset_name"] for c in configs}
    if len(datasets) != 1:
        raise ValueError(f"Eval configs disagree on the dataset: {sorted(datasets)}")
    dataset = datasets.pop()
    source = f"{DB}.EVALS.EVAL_SOURCE_DEMO_FINANCE_VS_SENSE"
    rows = []
    for n, q in enumerate(yaml.safe_load((demo / "demo_questions.yaml").read_text())["questions"], 1):
        gt = f"OBJECT_CONSTRUCT('ground_truth_output', {sql_str(q['ground_truth'].strip())})"
        rows.append(f"SELECT {n}, {sql_str(q['id'])}, {sql_str(q['bucket'])}, {sql_str(q.get('concept', ''))}, "
                    f"{sql_str(q['question'])}, TO_VARIANT({gt})")
    puts = "".join(f"PUT 'file://evaluations/demo/{c.name}' @{DB}.EVALS.EVAL_CONFIG AUTO_COMPRESS = FALSE OVERWRITE = TRUE;\n"
                   for c in configs)
    return (header("10-load-eval-dataset", "evaluations/demo/demo_questions.yaml and *_demo_eval.yaml")
            + f"-- Question bank -> {source} -> dataset {dataset} (the name comes from the eval configs).\n"
              "-- A dataset can't be overwritten: after changing questions or ground truth, bump the\n"
              "-- dataset_name suffix in all three *_demo_eval.yaml files and regenerate.\n\n"
            + f"CREATE OR REPLACE TABLE {source} (\n"
              "  QUESTION_ID NUMBER, DEMO_ID VARCHAR, BUCKET VARCHAR, CONCEPT VARCHAR, INPUT_QUERY VARCHAR, GROUND_TRUTH VARIANT\n);\n\n"
            + f"INSERT INTO {source}\n" + "\nUNION ALL ".join(rows) + ";\n\n"
            + f"CALL SYSTEM$CREATE_EVALUATION_DATASET('Cortex Agent', '{source}', '{dataset}',\n"
              "  OBJECT_CONSTRUCT('query_text', 'INPUT_QUERY', 'expected_tools', 'GROUND_TRUTH'));\n\n"
            + "-- Eval configs (agent, dataset, metric) read by EXECUTE_AI_EVALUATION\n" + puts)


GENERATED = {
    "02-load-data.sql": gen_02,
    "03-deploy-semantic-view.sql": gen_03,
    "05-prime-query-history.sql": gen_05,
    "07-create-context.sql": gen_07,
    "08-record-feedback.sql": gen_08,
    "09-deploy-agents.sql": gen_09,
    "10-load-eval-dataset.sql": gen_10,
}


def main():
    INSTALL.mkdir(exist_ok=True)
    for name, fn in GENERATED.items():
        text = fn()
        (INSTALL / name).write_text(text)
        print(f"Wrote install/{name} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
