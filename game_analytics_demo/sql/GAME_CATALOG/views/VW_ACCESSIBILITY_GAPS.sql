create or replace view CORTEX_SENSE_DEMO.GAME_CATALOG.VW_ACCESSIBILITY_GAPS(
	GAME_ID,
	GAME_NAME,
	FEATURE_ID,
	FEATURE_NAME,
	FEATURE_CATEGORY,
	IS_SUPPORTED
) as
SELECT
    g.GAME_ID, g.GAME_NAME,
    af.FEATURE_ID, af.FEATURE_NAME, af.FEATURE_CATEGORY,
    CASE WHEN ga.GAME_ID IS NOT NULL THEN TRUE ELSE FALSE END AS IS_SUPPORTED
FROM CORTEX_SENSE_DEMO.GAME_CATALOG.GAMES g
CROSS JOIN CORTEX_SENSE_DEMO.GAME_CATALOG.ACCESSIBILITY_FEATURES af
LEFT JOIN CORTEX_SENSE_DEMO.GAME_CATALOG.GAME_ACCESSIBILITY ga
  ON g.GAME_ID = ga.GAME_ID AND af.FEATURE_ID = ga.FEATURE_ID;
